#!/usr/bin/env python3
"""Count papers in _bibliography/papers.bib and write _data/pubstats.yml (used by the stat strips on the
Publications and Research pages). Run automatically by the deploy workflow; run by hand after editing the bib."""
import re, collections
text = open("_bibliography/papers.bib", encoding="utf-8").read()
entries = re.findall(r"@\w+\{[^@]*?\n\}\n", text, flags=re.S)
def field(e, k):
    m = re.search(r"^\s*%s\s*=\s*\{(.*)\},?$" % k, e, flags=re.M); return m.group(1) if m else ""
c = collections.Counter()
ML, NLP, CV, AI = {"NeurIPS", "ICML", "ICLR"}, {"ACL", "EMNLP", "NAACL", "COLM"}, {"CVPR", "ICCV", "ECCV"}, {"AAAI", "IJCAI"}
for e in entries:
    kw = field(e, "keywords"); abbr = field(e, "abbr").replace(" Findings", "")
    if "status:preprint;" in kw: c["preprints"] += 1; continue
    c["published"] += 1
    if re.search(r"^\s*journal\s*=", e, flags=re.M): c["journal"] += 1
    else: c["conference"] += 1
    if abbr in ML: c["ml"] += 1
    if abbr in NLP: c["nlp"] += 1
    if abbr in CV: c["cv"] += 1
    if abbr in AI: c["ai"] += 1
SECTIONS = {  # research-page section -> topic slugs (keep in sync with _pages/research.md)
    "llm": ["llm__data-selection-training-curriculum-and-synthetic-data","llm__post-training-and-reasoning","llm__human-ai-alignment-and-reward-hacking","llm__generalization","llm__prompting-and-test-time-optimization","llm__in-context-learning","llm__decoding","llm__retrieval-augmented-generation","llm__safety","llm__benchmarks-and-evaluation"],
    "mllm": ["mllm__model-architecture-and-training-recipe","mllm__post-training","mllm__benchmarks-and-evaluation","mllm__test-time-optimization","diffusion-models"],
    "agents": ["agents-and-world-models","reinforcement-learning"],
    "paradigms": ["curriculum-learning-and-data-selection","data-augmentation-and-synthesis","continual-learning-plasticity-stability-trade-off","transfer-learning-multi-task-learning-meta-learning","distributed-and-collaborative-learning"],
    "foundations": ["natural-language-processing","matrix-factorization-and-feature-disentanglement","compressed-sensing-sparse-dimension-reduction","optimization"],
}
sec = collections.Counter()
for e in entries:
    kw = field(e, "keywords")
    for name, slugs in SECTIONS.items():
        if any(f"topic:{sl};" in kw for sl in slugs): sec[name] += 1
lines = ["# Generated by scripts/pubstats.py from _bibliography/papers.bib — do not edit by hand."]
for k in ("published", "conference", "journal", "preprints", "ml", "nlp", "cv", "ai"): lines.append(f"{k}: {c[k]}")
lines.append("sections:")
for k in SECTIONS: lines.append(f"  {k}: {sec[k]}")
open("_data/pubstats.yml", "w").write("\n".join(lines) + "\n"); print(dict(c))
